#!/usr/bin/env python3
"""Generate thesis result tables from normalized experiment metrics."""

from __future__ import annotations

import argparse
import math
import os
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
ANALYSIS_DATA = Path(
    os.environ.get("DEEPRV_ANALYSIS_DATA_ROOT", ROOT / "analysis" / "data")
)
OUT = ROOT / "tables" / "generated"

TEACHERS = ["Bilinear", "Cubic", "DTC", "FITC"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--analysis-data",
        type=Path,
        default=ANALYSIS_DATA,
        help="Directory containing results_long.csv and results_aggregate.csv.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=OUT,
        help="Directory for generated LaTeX tables.",
    )
    return parser.parse_args()


def tex(value: str) -> str:
    return (
        value.replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
    )


def number(value: float, digits: int = 3) -> str:
    if value is None or not math.isfinite(float(value)):
        return "--"
    value = float(value)
    if abs(value) >= 1000:
        return f"{value:,.0f}"
    if abs(value) >= 100:
        return f"{value:.1f}"
    if abs(value) >= 10:
        return f"{value:.2f}"
    return f"{value:.{digits}f}"


def mean_sd(data: pd.DataFrame, model: str, metric: str, digits: int = 3) -> str:
    row = data[(data["model"] == model) & (data["metric"] == metric)]
    if row.empty or int(row.iloc[0]["n"]) == 0:
        return "--"
    mean = number(row.iloc[0]["mean"], digits)
    sd = number(row.iloc[0]["sample_sd"], digits)
    return mean if sd == "--" else f"{mean} ({sd})"


def write(name: str, lines: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main_summary(
    data: pd.DataFrame, grid: str, models: list[str], output: str
) -> None:
    sub = data[data["grid"] == grid]
    lines = [
        "% Generated by analysis/tables/build_result_tables.py",
        "% Source: analysis-ready results_aggregate.csv",
        r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule",
        r"Model & Predictive MSE & $W_1(\ell)$ & Unobserved 90\% & Total (s) \\",
        r"\midrule",
    ]
    for model in models:
        display_model = model.replace("DeepRV ", "")
        lines.append(
            f"{tex(display_model)} & "
            f"{mean_sd(sub, model, 'predictive_mse_vs_full_gp')} & "
            f"{mean_sd(sub, model, 'lengthscale_w1_vs_full_gp')} & "
            f"{mean_sd(sub, model, 'coverage_90_unobserved')} & "
            f"{mean_sd(sub, model, 'total_seconds', 1)} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    write(output, lines)


def runtime_table(data: pd.DataFrame) -> None:
    sub = data[data["grid"] == "64x64"]
    models = [
        "Full GP",
        "Exact DeepRV",
        "DeepRV Cubic 32",
        "Direct Cubic 32",
        "DeepRV FITC 32",
    ]
    lines = [
        "% Generated by analysis/tables/build_result_tables.py",
        "% Source: analysis-ready results_aggregate.csv",
        r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule",
        r"Model & Teacher fields & Optimisation & Inference & First use \\",
        r"\midrule",
    ]
    for model in models:
        lines.append(
            f"{tex(model)} & {mean_sd(sub, model, 'field_generation_seconds', 1)} & "
            f"{mean_sd(sub, model, 'training_seconds', 1)} & "
            f"{mean_sd(sub, model, 'inference_seconds', 1)} & "
            f"{mean_sd(sub, model, 'total_seconds', 1)} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    write("tab04_runtime64.tex", lines)


def sort_models(frame: pd.DataFrame) -> pd.DataFrame:
    family_order = {"Reference": 0, "DeepRV": 1, "Direct": 2}
    teacher_order = {"Full GP": -2, "Exact": -1, **dict(zip(TEACHERS, range(4)))}
    frame = frame.copy()
    frame["family_order"] = frame["family"].map(family_order)
    frame["teacher_order"] = frame["teacher"].map(teacher_order)
    columns = ["grid", "family_order", "teacher_order", "inducing_side"]
    if "seed" in frame.columns:
        columns.append("seed")
    return frame.sort_values(
        columns,
        na_position="first",
    )


def supplement_model(model: str) -> str:
    if model.startswith("DeepRV "):
        teacher, side = model.removeprefix("DeepRV ").rsplit(" ", 1)
        return f"{teacher}{side}"
    if model.startswith("Direct "):
        teacher, side = model.removeprefix("Direct ").rsplit(" ", 1)
        return f"Direct {teacher}{side}"
    return model


def supplementary_per_seed_table(
    long: pd.DataFrame,
    output: str,
    caption: str,
    label: str,
    metrics: list[tuple[str, str, int]],
) -> None:
    frame = sort_models(long.copy())
    column_spec = "@{}ll" + "r" * (1 + len(metrics)) + "@{}"
    header = ["Grid", "Model", "Seed"] + [title for _, title, _ in metrics]
    lines = [
        "% Generated by analysis/tables/build_result_tables.py",
        "% Source: analysis-ready results_long.csv",
        r"\begingroup",
        r"\setlength{\tabcolsep}{3pt}",
        rf"\begin{{longtable}}{{{column_spec}}}",
        rf"\caption{{{caption}}}\label{{{label}}}\\",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
        r"\endfirsthead",
        rf"\multicolumn{{{len(header)}}}{{c}}{{\tablename~\thetable{{}} (continued)}}\\",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
        r"\endhead",
        rf"\midrule\multicolumn{{{len(header)}}}{{r}}{{Continued on next page}}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    previous_grid = None
    previous_model = None
    for _, row in frame.iterrows():
        grid = str(row["grid"])
        model = str(row["model"])
        grid_cell = grid.replace("x", r"$\times$") if grid != previous_grid else ""
        model_cell = supplement_model(model) if model != previous_model else ""
        cells = [grid_cell, tex(model_cell), str(int(row["seed"]))]
        for metric, _, digits in metrics:
            cells.append(number(row[metric], digits))
        lines.append(" & ".join(cells) + r" \\")
        previous_grid = grid
        previous_model = model
    lines.extend([r"\end{longtable}", r"\endgroup"])
    write(output, lines)


def supplementary_runtime_k(data: pd.DataFrame) -> None:
    models = [
        "Full GP",
        "Exact DeepRV",
        "DeepRV Cubic 32",
        "Direct Cubic 32",
        "DeepRV FITC 32",
    ]
    k_values = [1, 2, 5, 10, 20, 50]

    def aggregate(model: str, metric: str) -> float:
        row = data[
            (data["grid"] == "64x64")
            & (data["model"] == model)
            & (data["metric"] == metric)
        ]
        if len(row) != 1:
            raise RuntimeError(f"Missing runtime input: {model}, {metric}")
        return float(row.iloc[0]["mean"])

    lines = [
        "% Generated by analysis/tables/build_result_tables.py",
        "% Source: analysis-ready results_aggregate.csv",
        r"\begin{longtable}{@{}lrrr@{}}",
        r"\caption{Inputs to the 64x64 repeated-use calculation. For Full GP and Direct GP, cumulative time is $K T_{\mathrm{inference}}$; for DeepRV it is $T_{\mathrm{pretrain}}+K T_{\mathrm{inference}}$.}\label{tab:supp-runtime-k}\\",
        r"\toprule",
        r"Model & $K$ & Cumulative (s) & Mean per dataset (s) \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Model & $K$ & Cumulative (s) & Mean per dataset (s) \\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for model in models:
        inference = aggregate(model, "inference_seconds")
        total = aggregate(model, "total_seconds")
        pretrain = 0.0 if model == "Full GP" or model.startswith("Direct ") else total - inference
        for index, k in enumerate(k_values):
            cumulative = pretrain + k * inference
            lines.append(
                f"{tex(model) if index == 0 else ''} & {k} & "
                f"{number(cumulative, 1)} & {number(cumulative / k, 1)} \\\\"
            )
    lines.append(r"\end{longtable}")
    write("tabS07_runtime_k.tex", lines)


