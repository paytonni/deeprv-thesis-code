def aggregate_value(
    data: pd.DataFrame,
    *,
    study: str,
    grid: str,
    model: str,
    metric: str,
    true_lengthscale: float = 30.0,
) -> float:
    rows = data[
        (data["study"] == study)
        & (data["grid"] == grid)
        & (data["model"] == model)
        & (data["metric"] == metric)
        & (data["true_lengthscale"] == true_lengthscale)
    ]
    if len(rows) != 1:
        raise RuntimeError(
            "Expected one three-seed aggregate for "
            f"{study}/{grid}/{model}/{true_lengthscale:g}/{metric}; found {len(rows)}"
        )
    row = rows.iloc[0]
    if int(row["n"]) != 3:
        raise RuntimeError(
            f"Expected Seeds 0, 1 and 2 for {study}/{grid}/{model}/{metric}"
        )
    return float(row["mean"])


def table16_predictive_mse(value: float) -> str:
    return f"{value:.5f}" if abs(value) < 0.01 else number(value, 3)


