def supplementary_exploratory_table() -> None:
    data = pd.read_csv(EXPLORATORY)
    metric_names = {
        "coverage_90_unobserved": "Unobs. coverage",
        "lengthscale_wasserstein_vs_full_gp": "$W_1(\\ell)$",
        "measured_pretraining_cost_saving_vs_exact": "Pretrain saving",
        "posterior_mean_log1p_rmse_vs_full_gp": "log1p mean RMSE",
        "posterior_mean_mse_vs_full_gp": "Predictive MSE",
        "relative_lengthscale_wasserstein_vs_full_gp": "Relative $W_1$",
    }
    teacher_order = {"Full GP": 0, "Exact": 1, "Lowres": 2, "Local": 3}
    data = data.assign(
        teacher_order=data["teacher"].map(teacher_order).fillna(9),
        side_order=pd.to_numeric(data["inducing_grid_size"], errors="coerce"),
    ).sort_values(
        ["target_resolution", "true_lengthscale", "teacher_order", "side_order", "metric_name"],
        na_position="first",
    )
    lines = [
        "% Generated by scripts/tables/build_result_tables.py",
        "% Source: evidence_snapshot/data_for_plots/8x8_16x16_exploratory_metrics.csv",
        r"\begin{longtable}{@{}lllllrl@{}}",
        r"\caption{Complete retained 8x8 and 16x16 exploratory evidence. Values are aggregates over Seeds 0, 1 and 2; eligibility refers to use in the main-text recommendation.}\label{tab:supp-exploratory-evidence}\\",
        r"\toprule",
        r"Grid & Teacher & Side & $\ell_0$ & Metric & Value & Eligible \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Grid & Teacher & Side & $\ell_0$ & Metric & Value & Eligible \\",
        r"\midrule",
        r"\endhead",
        r"\midrule\multicolumn{7}{r}{Continued on next page}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for _, row in data.iterrows():
        side = "--" if str(row["inducing_grid_size"]) == "NOT_APPLICABLE" else str(row["inducing_grid_size"])
        eligible = "Yes" if bool(row["eligible_for_main_text"]) else "No"
        grid_label = str(row["target_resolution"]).replace("x", r"$\times$")
        teacher_label = (
            "Low-resolution" if str(row["teacher"]) == "Lowres" else str(row["teacher"])
        )
        lines.append(
            f"{grid_label} & "
            f"{tex(teacher_label)} & {side} & {number(row['true_lengthscale'], 0)} & "
            f"{metric_names[str(row['metric_name'])]} & {number(row['metric_value'], 4)} & {eligible} \\\\"
        )
    lines.append(r"\end{longtable}")
    write("tabS08_exploratory_evidence.tex", lines)


def supplementary_aggregate_table(data: pd.DataFrame) -> None:
    models = data[
        ["grid", "model", "family", "teacher", "inducing_side"]
    ].drop_duplicates()
    models = sort_models(models)

    def cell(grid: str, model: str, metric: str, digits: int = 3) -> str:
        row = data[
            (data["grid"] == grid)
            & (data["model"] == model)
            & (data["metric"] == metric)
        ]
        if row.empty or int(row.iloc[0]["n"]) == 0:
            return "--"
        a = number(row.iloc[0]["mean"], digits)
        b = number(row.iloc[0]["sample_sd"], digits)
        return a if b == "--" else f"{a} ({b})"

    lines = [
        "% Generated by scripts/tables/build_result_tables.py",
        "% Source: evidence_overrides/generated/results_aggregate_author_corrected.csv",
        r"\begingroup",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\begin{longtable}{@{}llrrrr@{}}",
        r"\caption{Complete 32x32 and 64x64 aggregate results. Values are mean (sample SD) over Seeds 0, 1 and 2. Approximate rows without a Direct prefix are DeepRV models.}\label{tab:supp-all-aggregates}\\",
        r"\toprule",
        r"Grid & Model & Predictive MSE & $W_1(\ell)$ & Unobs. 90\% & Total (s) \\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{6}{c}{\tablename~\thetable{} (continued)}\\",
        r"\toprule",
        r"Grid & Model & Predictive MSE & $W_1(\ell)$ & Unobs. 90\% & Total (s) \\",
        r"\midrule",
        r"\endhead",
        r"\midrule\multicolumn{6}{r}{Continued on next page}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    current_grid = None
    for _, row in models.iterrows():
        grid = str(row["grid"])
        model = str(row["model"])
        grid_label = grid.replace("x", r"$\times$") if grid != current_grid else ""
        lines.append(
            f"{grid_label} & "
            f"{tex(supplement_model(model))} & "
            f"{cell(grid, model, 'predictive_mse_vs_full_gp')} & "
            f"{cell(grid, model, 'lengthscale_w1_vs_full_gp')} & "
            f"{cell(grid, model, 'coverage_90_unobserved')} & "
            f"{cell(grid, model, 'total_seconds', 1)} \\\\"
        )
        current_grid = grid
    lines.extend([r"\end{longtable}", r"\endgroup"])
    write("tabS02_all_aggregate_results.tex", lines)


def direct_pair_table(long: pd.DataFrame) -> None:
    frame = long[long["grid"] == "64x64"].copy()
    lines = [
        "% Generated by scripts/tables/build_result_tables.py",
        "% Source: evidence_overrides/generated/results_long_author_corrected.csv",
        r"\begin{longtable}{@{}llrrrr@{}}",
        r"\caption{Matched 64x64 DeepRV and Direct GP comparisons. Values are paired means over the same three seeds.}\label{tab:supp-direct-pairs}\\",
        r"\toprule",
        r"Teacher & Side & DeepRV MSE & Direct MSE & DeepRV $W_1$ & Direct $W_1$ \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Teacher & Side & DeepRV MSE & Direct MSE & DeepRV $W_1$ & Direct $W_1$ \\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for teacher in TEACHERS:
        for side in (8, 16, 32):
            deep = frame[frame["model"] == f"DeepRV {teacher} {side}"].sort_values("seed")
            direct = frame[frame["model"] == f"Direct {teacher} {side}"].sort_values("seed")
            if list(deep["seed"]) != [0, 1, 2] or list(direct["seed"]) != [0, 1, 2]:
                raise RuntimeError(f"Incomplete Direct pair: {teacher} {side}")
            lines.append(
                f"{teacher if side == 8 else ''} & {side} & "
                f"{number(deep['predictive_mse_vs_full_gp'].mean())} & "
                f"{number(direct['predictive_mse_vs_full_gp'].mean())} & "
                f"{number(deep['lengthscale_w1_vs_full_gp'].mean())} & "
                f"{number(direct['lengthscale_w1_vs_full_gp'].mean())} \\\\"
            )
    lines.append(r"\end{longtable}")
    write("tabS03_direct_pairs.tex", lines)


def main() -> None:
    data = pd.read_csv(AGGREGATES)
    long = pd.read_csv(LONG)
    main_summary(
        data,
        "32x32",
        ["Full GP", "Exact DeepRV"]
        + [f"DeepRV {teacher} 16" for teacher in TEACHERS],
        "tab02_grid32_summary.tex",
    )
    main_summary(
        data,
        "64x64",
        ["Full GP", "Exact DeepRV"]
        + [f"DeepRV {teacher} 32" for teacher in TEACHERS]
        + ["DeepRV FITC 16"],
        "tab03_grid64_summary.tex",
    )
    runtime_table(data)
    supplementary_aggregate_table(data)
    direct_pair_table(long)
    supplementary_per_seed_table(
        long,
        "tabS04_per_seed_fidelity.tex",
        "Complete per-seed fidelity and diagnostic classifications for the 32x32 and 64x64 studies.",
        "tab:supp-per-seed-fidelity",
        [
            ("predictive_mse_vs_full_gp", "Predictive MSE", 3),
            ("lengthscale_w1_vs_full_gp", "$W_1(\\ell)$", 3),
            ("posterior_lengthscale_mean", "$\\bar\\ell$", 3),
            ("posterior_lengthscale_sd", "SD($\\ell$)", 3),
        ],
        include_gate=True,
    )
    supplementary_per_seed_table(
        long,
        "tabS05_per_seed_predictive.tex",
        "Complete per-seed secondary predictive results for the 32x32 and 64x64 studies.",
        "tab:supp-per-seed-predictive",
        [
            ("log1p_mse_counts", "Count MSE", 3),
            ("coverage_90_all", "All 90\\%", 3),
            ("coverage_90_unobserved", "Unobs. 90\\%", 3),
        ],
        include_gate=True,
    )
    supplementary_per_seed_table(
        long,
        "tabS06_per_seed_runtime.tex",
        "Complete per-seed measured runtime components for the 32x32 and 64x64 studies.",
        "tab:supp-per-seed-runtime",
        [
            ("field_generation_seconds", "Fields", 1),
            ("training_seconds", "Optimisation", 1),
            ("inference_seconds", "Inference", 1),
            ("total_seconds", "Total", 1),
        ],
    )
    supplementary_runtime_k(data)
    supplementary_exploratory_table()
    supplementary_diagnostic_table(long)


if __name__ == "__main__":
    main()
